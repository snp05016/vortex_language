def self_test():
    # Relative links, as seen from the page that includes the snippet.
    stage3 = "compiler/guide/stage-3-parser-and-tree.md"
    assert relative_link("compiler/guide/stage-2-lexer.md", stage3) == "stage-2-lexer.md"
    assert relative_link("language-tour/08-expressions.md", stage3) == "../../language-tour/08-expressions.md"
    assert relative_link("specification/conformance.md#14-x", stage3) == "../../specification/conformance.md#14-x"
    assert relative_link("index.md", stage3) == "../../index.md"
    assert relative_link("compiler/guide/index.md", "index.md") == "compiler/guide/index.md"
    assert relative_link("language-tour/README.md", "language-tour/04-variables-and-types.md") == "README.md"
    assert page_key(stage3) == "compiler__guide__stage-3-parser-and-tree"
    assert slugify("1.4 Static and dynamic rules", "-") == "14-static-and-dynamic-rules"

    # Tooltip filter: abbreviations and multi-word terms only, never one plain word.
    def concept(**fields):
        return {"aliases": [], "short": "Tip.", **fields}

    assert tooltip_keys(concept(term="type")) == {}
    assert tooltip_keys(concept(term="type", tooltip=True)) == {}  # validate() reports this
    assert tooltip_keys(concept(term="basic block")) == {}  # multi-word terms opt in
    keys = tooltip_keys(concept(term="abstract syntax tree", abbr="AST", aliases=["syntax diagram", "tree"]))
    assert keys == {"AST": "abstract syntax tree: Tip.", "abstract syntax tree": "Tip.", "syntax diagram": "Tip."}
    assert tooltip_keys(concept(term="UTF-8", abbr="UTF-8")) == {"UTF-8": "Tip."}
    assert tooltip_keys(concept(term="Pratt parsing", tooltip=True)) == {"Pratt parsing": "Tip."}
    assert tooltip_keys(concept(term="IEEE 754", abbr="IEEE 754", tooltip=False)) == {}
    assert tooltip_keys(concept(term="token", aliases=["lexeme"], abbr="TOK")) == {"TOK": "token: Tip."}

    # Scanning ignores code and link targets, and accepts plurals and hyphen/space variants.
    text = prose("A basic-block ends.\n```\nbasic block\n```\n[x](basic-block.md) and `basic block`. Basic blocks!")
    assert sum(len(p.findall(text)) for p in scan_patterns(concept(term="basic block"))) == 2

    # Local concept map: this page's concepts, their direct prerequisites and
    # direct dependents, with edges only between nodes actually shown.
    def linked(cid, term, page, requires=()):
        return concept(id=cid, term=term, introduced_in=page, requires=list(requires), used_in=[])

    nav = [{"path": p, "title": p, "section": ""} for p in ("n0.md", "n1.md", "n2.md", "n3.md")]
    small = Memory(
        {
            "concepts": [
                linked("a", "A", "n0.md"),
                linked("b", "B", "n1.md", ["a"]),
                linked("c", "C", "n1.md", ["a"]),
                linked("d", "D", "n2.md", ["b"]),
                linked("e", "E", "n3.md"),
            ],
            "review_groups": [],
        },
        nav,
    )
    assert small.local_map("nowhere.md") == ""  # introduces nothing
    assert small.local_map("n3.md") == 'flowchart LR\n  c_e["E"]\n'  # no requires, nothing depends on it
    assert (
        small.local_map("n1.md")
        == "\n".join(
            [
                "flowchart LR",
                '  c_b["B"]',
                '  c_c["C"]',
                '  c_a["A"]',
                '  c_d["D"]',
                "  c_a --> c_b",
                "  c_a --> c_c",
                "  c_b --> c_d",
            ]
        )
        + "\n"
    )
    # A page with neither a "next" list nor a graph stays empty; one with
    # only a graph still gets the collapsed box, indented under it.
    assert small.next_pages("nowhere.md") == ""
    assert small.next_pages("n3.md") == (
        f"<!-- {NOTICE} -->\n\n"
        '??? info "Concept map for this page"\n\n'
        "    ```mermaid\n"
        "    flowchart LR\n"
        '      c_e["E"]\n'
        "    ```\n"
    )

    # The cap: every concept a page introduces is kept even past it, but
    # prerequisites and dependents split whatever budget is left.
    pages = [{"path": p, "title": p, "section": ""} for p in ("p0.md", "p1.md", "big.md")]
    hub = [linked("r", "Root", "p0.md")] + [linked(f"dep{i}", f"D{i}", "p1.md", ["r"]) for i in range(20)]
    assert Memory({"concepts": hub, "review_groups": []}, pages).local_map("p0.md").count("[") == LOCAL_MAP_MAX
    overflow = [linked(f"h{i}", f"H{i}", "big.md") for i in range(LOCAL_MAP_MAX + 3)]
    over_map = Memory({"concepts": overflow, "review_groups": []}, pages).local_map("big.md")
    assert over_map.count("[") == LOCAL_MAP_MAX + 3


